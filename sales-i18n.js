const LANG_ALIASES = {
  "pt-br": "pt",
  "pt-pt": "pt",
  "zh-cn": "zh",
  "zh-hans": "zh",
  "zh-tw": "zh",
  "zh-hant": "zh",
  "fil": "tl",
  "tl-ph": "tl",
  "tr": "tur"
};

function resolveSalesLanguage(raw) {
  if (!raw) return "en";
  const norm = String(raw).trim().toLowerCase().replace(/_/g, "-");
  if (translations[norm]) return norm;
  if (LANG_ALIASES[norm]) return LANG_ALIASES[norm];
  const base = norm.split("-")[0];
  if (translations[base]) return base;
  if (LANG_ALIASES[base]) return LANG_ALIASES[base];
  return "en";
}

function detectSalesLanguage() {
  const candidates = [];
  if (Array.isArray(navigator.languages)) candidates.push(...navigator.languages);
  if (navigator.language) candidates.push(navigator.language);
  for (const raw of candidates) {
    const code = resolveSalesLanguage(raw);
    if (code !== "en" || String(raw).toLowerCase().startsWith("en")) return code;
    if (translations[code]) return code;
  }
  return "en";
}

function getInitialSalesLanguage() {
  try {
    const saved = localStorage.getItem(SALES_LANG_STORAGE_KEY);
    if (saved && translations[resolveSalesLanguage(saved)]) {
      return resolveSalesLanguage(saved);
    }
  } catch (_) { /* private mode */ }
  return detectSalesLanguage();
}

function applyLanguage(langCode, options) {
  const opts = options || {};
  const lang = resolveSalesLanguage(langCode);
  const pack = translations[lang] || translations.en;
  const rtl = RTL_LANGS.has(lang);

  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", rtl);

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    const text = pack[key];
    if (text != null) el.textContent = text;
  });

  document.querySelectorAll("#sales-lang-list [role='option']").forEach(function (item) {
    const active = item.getAttribute("data-lang") === lang;
    item.setAttribute("aria-selected", active ? "true" : "false");
    item.classList.toggle("bg-brand-50", active);
    item.classList.toggle("text-brand-700", active);
    item.classList.toggle("font-semibold", active);
  });

  if (opts.persist !== false) {
    try {
      localStorage.setItem(SALES_LANG_STORAGE_KEY, lang);
    } catch (_) { /* private mode */ }
  }
}

function closeSalesLangMenu() {
  const btn = document.getElementById("sales-lang-btn");
  const list = document.getElementById("sales-lang-list");
  if (!list || !btn) return;
  list.classList.add("hidden");
  btn.setAttribute("aria-expanded", "false");
}

function openSalesLangMenu() {
  const btn = document.getElementById("sales-lang-btn");
  const list = document.getElementById("sales-lang-list");
  if (!list || !btn) return;
  list.classList.remove("hidden");
  btn.setAttribute("aria-expanded", "true");
}

function toggleSalesLangMenu() {
  const list = document.getElementById("sales-lang-list");
  if (!list) return;
  if (list.classList.contains("hidden")) openSalesLangMenu();
  else closeSalesLangMenu();
}

function initSalesLanguageUI() {
  const btn = document.getElementById("sales-lang-btn");
  const list = document.getElementById("sales-lang-list");
  const menu = document.getElementById("sales-lang-menu");

  if (!btn || !list) {
    applyLanguage(getInitialSalesLanguage());
    return;
  }

  if (!list.children.length) {
    SALES_LANG_OPTIONS.forEach(function (opt) {
      if (!translations[opt.code]) return;
      const li = document.createElement("li");
      li.setAttribute("role", "option");
      li.setAttribute("data-lang", opt.code);
      li.setAttribute("aria-selected", "false");
      li.tabIndex = 0;
      li.className =
        "cursor-pointer px-4 py-2.5 text-sm text-slate-700 transition hover:bg-slate-50 hover:text-brand-700";
      li.textContent = opt.label;
      li.addEventListener("click", function () {
        applyLanguage(opt.code);
        closeSalesLangMenu();
      });
      li.addEventListener("keydown", function (e) {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          applyLanguage(opt.code);
          closeSalesLangMenu();
        }
      });
      list.appendChild(li);
    });
  }

  btn.addEventListener("click", function (e) {
    e.stopPropagation();
    toggleSalesLangMenu();
  });

  document.addEventListener("click", function (e) {
    if (menu && !menu.contains(e.target)) closeSalesLangMenu();
  });

  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape") closeSalesLangMenu();
  });

  applyLanguage(getInitialSalesLanguage());
}

